-- 003_role_varchar.sql
-- تغییر role از enum به varchar برای پشتیبانی از نقش‌های جدید
-- ═══════════════════════════════════════════════════════════

ALTER TABLE `complex_members`
MODIFY COLUMN `role` VARCHAR(20) NOT NULL DEFAULT 'employee';

-- ═══════════════════════════════════════════════════════════
-- اطمینان از اینکه مالک‌ها با role درست ذخیره شدن
-- ═══════════════════════════════════════════════════════════

UPDATE `complex_members`
SET `role` = 'owner'
WHERE `role` = 'both';