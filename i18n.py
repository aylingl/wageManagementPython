def set_language(lang):
    global _current_lang
    if lang in ("fa", "en", "ar"):
        _current_lang = lang

def get_language():
    return _current_lang

def tr(key, **kwargs):
    lang_dict = TRANSLATIONS.get(_current_lang, TRANSLATIONS["fa"])
    text = lang_dict.get(key, key)

    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text

    return text